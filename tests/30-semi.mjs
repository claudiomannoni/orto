// La banca dei semi: aggiungere una bustina, vedere cosa seminare nel mese, toglierla. Uso: node tests/30-semi.mjs http://localhost:8101
import { chromium, nuovoContesto, check, osserva, finale, vai } from './lib.mjs';
const browser = await chromium.launch();
const problemi = [];
const ctx = await nuovoContesto(browser, { serviceWorkers: 'block' });
const page = await ctx.newPage();
osserva(page, problemi);
page.on('dialog', (d) => d.accept());
await vai(page, 'scopri', '?oggi=2026-03-10');
await page.click('a.tessera-scopri[href="#/semi"]');
await page.waitForSelector('#semi-nuova');
check('la barra tiene acceso «Scopri»', (await page.locator('#barra a[aria-current=page]').innerText()).includes('Scopri'));
check('all\'inizio nessuna bustina e un invito', /Non hai ancora segnato/.test(await page.locator('main').innerText()));
check('lista della spesa: a marzo manca la bustina di cose seminabili (prima di aggiungere i pomodori)', /Lista della spesa/.test(await page.locator('main').innerText()));
await page.click('#semi-nuova');
await page.waitForSelector('dialog[open] select[name=scheda]');
await page.selectOption('dialog select[name=scheda]', 'pomodori');
await page.fill('dialog input[name=anno]', '2020');
await page.fill('dialog input[name=quantita]', 'mezza bustina');
await page.click('dialog button[type=submit]');
await page.waitForSelector('li.seme');
const testo = await page.locator('li.seme').first().innerText();
check('la bustina compare con nome, anno e quantità', /Pomodor/.test(testo) && /2020/.test(testo) && /mezza bustina/.test(testo), testo);
check('semi del 2020: compaiono in «Semi da rinnovare»', /Semi da rinnovare/.test(await page.locator('main').innerText()));
check('semi del 2020: avviso «vecchi», nessuna promessa sulla germinazione', /Semi vecchi/.test(testo) && !/%/.test(testo));
check('a marzo i pomodori si possono seminare: sezione «Da seminare questo mese»', /Da seminare questo mese/.test(await page.locator('main').innerText()));
await page.reload();
await page.waitForSelector('li.seme');
check('la bustina resta dopo aver ricaricato', (await page.locator('li.seme').count()) === 1);
await page.click('li.seme button');
await page.waitForFunction(() => !document.querySelector('li.seme'));
check('si toglie con conferma', /Non hai ancora segnato/.test(await page.locator('main').innerText()));
const veri = problemi.filter((p) => !/Service Worker registration blocked/.test(p));
check('nessun errore in console', veri.length === 0, veri.join(' | '));
await browser.close();
process.exit(finale() ? 1 : 0);
