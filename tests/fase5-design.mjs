// Contratto statico del nuovo disegno, eseguibile senza browser.
import fs from 'node:fs';
const read = (p) => fs.readFileSync(new URL(`../${p}`, import.meta.url), 'utf8');
const tokens = read('css/tokens.css');
const css = read('css/app.css');
const nav = read('js/ui/nav.js');
const oggi = read('js/screens/oggi.js');
const colture = read('js/screens/colture.js');
const pianta = read('js/screens/pianta.js');
const bustina = read('js/ui/bustina-pianta.js');
const it = JSON.parse(read('i18n/it.json'));
const versione = read('js/versione.js');
const cache = read('sw.js');
const appVersione = versione.match(/APP_VERSIONE\s*=\s*'([^']+)'/)?.[1];
const cacheVer = appVersione && cache.includes(`const VERSIONE = 'orto-${appVersione}'`) ? appVersione : null;
let ok = 0, ko = 0;
const check = (nome, valido) => { valido ? ok++ : ko++; console.log(`${valido ? 'PASS' : 'FAIL'} ${nome}`); };

check('token: dimensioni tocco e riga', /--tocco:\s*56px/.test(tokens) && /--riga:\s*48px/.test(tokens));
check('token: palette chiara/scura e quattro nuovi accenti', ['#EEF4EA', '#101A13', '#6B4430', '--pomodoro', '--zucca', '--cielo'].every((v) => tokens.includes(v)));
check('testata: non rende motto né icona vermi', !nav.includes("t('app.slogan')") && !nav.includes("class: 'gioco-vermi'"));
check('barra: cinque voci con etichetta visibile', nav.includes("export const ROTTE = ['oggi', 'colture', 'dottore', 'calendario', 'scopri']") && /el\(['"]span['"], \{\}, t\(`nav\.\$\{rotta\}`\)\)/.test(nav));
check('Oggi: lavori, meteo, bustine, scorciatoie e Per te', ['oggi.da_fare', 'cartaMeteo()', 'bustinaPianta(', 'oggi.scorciatoia.foto', 'oggi.per_te'].every((v) => oggi.includes(v)) && read('js/ui/meteo.js').includes('meteo-icona'));
check('colture: filtri, viste, registro e aggiunta fissa', ['colture-registro', 'colture.elenco', 'colture.mappa', 'colture-nuova-fissa', 'valutaSalute'].every((v) => colture.includes(v)));
check('bustina: fascia di stato, icona, nome e fase/età', ['bustina-pianta-fascia', "class: 'anello'", 'bustina-pianta-nome', 'bustina-pianta-meta'].every((v) => bustina.includes(v)) && pianta.includes('bustinaPianta('));
check('CSS: riduzione movimento e misure compatte', css.includes('@media (prefers-reduced-motion: reduce)') && css.includes('height: calc(64px + env(safe-area-inset-bottom))') && css.includes('min-height: 64px'));
check('CSS: regole bento e dock precedenti rimosse', !css.includes('.bento') && !css.includes('.dock'));
check('traduzioni nuove presenti', ['oggi.da_fare', 'oggi.altri_lavori', 'colture.mappa', 'colture.elenco', 'colture.piu_pianta'].every((k) => typeof it[k] === 'string'));
check(`versione app coerente con la cache (${cacheVer})`, Boolean(cacheVer));
check('cache offline aggiornata: bustina incluso', cache.includes("'./js/ui/bustina-pianta.js'"));
console.log(`Totale: ${ok} PASS, ${ko} FAIL`);
process.exit(ko ? 1 : 0);
