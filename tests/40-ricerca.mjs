import { chromium, nuovoContesto, check, osserva, finale, vai } from './lib.mjs';
const browser = await chromium.launch();
const problemi = [];
const ctx = await nuovoContesto(browser, { serviceWorkers: 'block' });
const page = await ctx.newPage();
osserva(page, problemi);
await vai(page, 'oggi');
await page.locator('.ricerca-apri').click();
await page.locator('input[name=ricerca]').fill('pomodro');
await page.waitForTimeout(150);
check('ricerca tollerante trova la scheda delle colture', await page.locator('.risultato-ricerca[href^="#/coltura"]').count() > 0);
await page.locator('input[name=ricerca]').fill('lombric');
check('ricerca raggruppa gli animali', await page.locator('.gruppo-ricerca').filter({ hasText: 'Animali' }).count() > 0);
await page.setViewportSize({ width: 360, height: 800 });
check('nessuno scroll orizzontale a 360 px', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
const errori = problemi.filter((p) => !/Service Worker registration blocked/.test(p));
check('nessun errore in console', errori.length === 0, errori.join(' | '));
await browser.close();
process.exit(finale() ? 1 : 0);
